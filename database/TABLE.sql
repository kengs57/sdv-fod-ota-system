CREATE TABLE member (
	MEMBER_NUM	NUMBER(10,0)		NOT NULL,
	ID	VARCHAR2(100 BYTE)		NOT NULL,
	PASSWORD	VARCHAR2(200 BYTE)		NULL,
	NAME	VARCHAR2(15 BYTE)		NULL,
	EMAIL	VARCHAR2(30 BYTE)		NULL,
	GENDER	VARCHAR2(15 BYTE)		NULL,
	SIGN_UP_DATE	DATE		NULL
);

CREATE TABLE vehicles_owned (
	VIN	VARCHAR2(18 BYTE)		NULL,
	CAR_MODEL	VARCHAR2(30 BYTE)		NULL,
	MEMBER_NUM	NUMBER(10,0)		NOT NULL
);

CREATE TABLE order_history (
	ORDER_NUM	NUMBER(20,0)		NOT NULL,
	ORDER_TIME	DATE		NULL,
	ORDER_STATUS	CHAR(1)		NULL,
	VIN	VARCHAR2(18 BYTE)		NULL,
	MEMBER_NUM	NUMBER(10,0)		NOT NULL,
	FEATURES_NUM	NUMBER(10,0)		NOT NULL
);

CREATE TABLE car_features (
	FEATURES_NUM	NUMBER(10,0)		NOT NULL,
	FEATURES_NAME	VARCHAR2(100 BYTE)		NULL,
	SUPPORTED_CAR_MODEL	VARCHAR2(30 BYTE)		NULL,
	PRICE	NUMBER(10,2)		NULL
);

CREATE TABLE sw_version (
	SW_NAME	VARCHAR2(30 BYTE)		NULL,
	LATEST_VERSION	VARCHAR2(30 BYTE)		NULL
);

ALTER TABLE member ADD CONSTRAINT PK_MEMBER PRIMARY KEY (
	MEMBER_NUM
);

ALTER TABLE vehicles_owned ADD CONSTRAINT PK_VEHICLES_OWNED PRIMARY KEY (
	VIN
);

ALTER TABLE order_history ADD CONSTRAINT PK_ORDER_HISTORY PRIMARY KEY (
	ORDER_NUM
);

ALTER TABLE car_features ADD CONSTRAINT PK_CAR_FEATURES PRIMARY KEY (
	FEATURES_NUM
);

ALTER TABLE sw_version ADD CONSTRAINT PK_SW_VERSION PRIMARY KEY (
	SW_NAME
);
