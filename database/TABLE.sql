SET LAST_UPDATED = (
    SELECT m.SIGN_UP_DATE + 5 
    FROM member m 
    WHERE m.MEMBER_NUM = (f.FEATURES_NUM - 100) -- 101번 기능은 1번 멤버 날짜 사용
);

-- sw_version: 최신 SW 순서대로 최근 가입자 날짜 매칭
